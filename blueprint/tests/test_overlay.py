"""What the overlay puts in a project, and what it is allowed to say.

Spec 2.1: the overlay's tree is copied into projects, and a `*.j2` file is rendered with the
spec 6.2 context and loses the suffix. So every path here lands in a project beside the files
core copies, and every name a template reads has to be one the tool passes.
"""

import re
import tomllib
from pathlib import Path
from typing import Any

import pytest
from jinja2 import Environment, FileSystemLoader, StrictUndefined, meta

REPO_ROOT = Path(__file__).resolve().parents[2]

CATALOG = tomllib.loads((REPO_ROOT / "blueprint.toml").read_text())

OVERLAY = REPO_ROOT / CATALOG["blueprint"]["overlay"]

CONTEXT_NAMES = {"project", "blueprint", "fastro", "features", "options", "services", "params", "has"}
"""Spec 6.2, in full. A template reaching for anything else fails under `StrictUndefined`."""

BUILT_IN_COMMANDS = {"add", "check", "eject", "features", "init", "make", "new", "remove", "sync", "update"}
"""Fastro's own verbs. Anything else after `fastro` has to be a command the catalog declares."""

A_FASTRO_COMMAND = re.compile(r"\bfastro ((?:[a-z][a-z0-9-]*)(?: [a-z][a-z0-9-]*)?)")

A_CODE_SPAN = re.compile(r"`([^`\n]+)`|```[a-z]*\n(.*?)```", re.DOTALL)
"""Only what is written as code is read as a command: prose says "generated by fastro from
blueprint.toml", and `fastro from` is not a command anybody runs. Each span is read on its own,
or two of them in one sentence would read as one command."""


def _context(features: tuple[str, ...] = (), **options: str) -> dict[str, Any]:
    """The spec 6.2 context, as the tool builds it for the overlay: no generator params."""
    return {
        "project": {"name": "Example App", "slug": "example-app"},
        "blueprint": {"name": CATALOG["blueprint"]["name"], "version": CATALOG["blueprint"]["version"]},
        "fastro": {"version": "0.1.0"},
        "features": list(features),
        "options": dict(options),
        "services": [],
        "params": {},
        "has": lambda name: name in features,
    }


def _files() -> list[Path]:
    return sorted(path for path in OVERLAY.rglob("*") if path.is_file())


def _declared_commands() -> set[str]:
    """Every command the catalog declares, the features' own included."""
    words = set(CATALOG.get("commands", {}))
    for feature in CATALOG["features"].values():
        words.update(feature.get("commands", {}))

    return words


def _withheld(path: str) -> bool:
    return any(
        path == entry.rstrip("/") or (entry.endswith("/") and path.startswith(entry))
        for entry in CATALOG["blueprint"]["blueprint_only"]
    )


def test_the_overlay_is_where_the_catalog_says():
    assert OVERLAY.is_dir()
    assert _files(), OVERLAY


@pytest.mark.parametrize("path", [str(path.relative_to(OVERLAY)) for path in _files()])
def test_no_overlay_file_lands_on_a_file_a_project_already_receives(path: str):
    """Two files at one path, and nothing says which wins: the overlay's `.gitignore` is the
    project's, so this repository's own is `blueprint_only` and never copied."""
    landing = Path(path)
    written = landing.with_suffix("") if landing.suffix == ".j2" else landing

    assert not (REPO_ROOT / written).exists() or _withheld(written.as_posix()), written.as_posix()


@pytest.mark.parametrize("path", [str(path.relative_to(OVERLAY)) for path in _files() if path.suffix == ".j2"])
def test_every_template_reads_only_what_the_tool_passes(path: str):
    """Spec 6.2: the context is fixed, so a template that asks for anything else renders nothing."""
    environment = Environment(loader=FileSystemLoader(OVERLAY), undefined=StrictUndefined, keep_trailing_newline=True)
    source = environment.loader.get_source(environment, path)[0]

    assert meta.find_undeclared_variables(environment.parse(source)) <= CONTEXT_NAMES


@pytest.mark.parametrize("path", [str(path.relative_to(OVERLAY)) for path in _files() if path.suffix == ".j2"])
def test_every_template_renders_for_a_project_with_no_features(path: str):
    """Core only is the harshest selection: every feature's lines have to be behind a condition."""
    environment = Environment(loader=FileSystemLoader(OVERLAY), undefined=StrictUndefined, keep_trailing_newline=True)

    assert environment.get_template(path).render(_context()).strip()


@pytest.mark.parametrize("path", [str(path.relative_to(OVERLAY)) for path in _files()])
def test_every_fastro_command_the_overlay_names_is_one_a_project_has(path: str):
    """A project told to run a command its blueprint doesn't declare is a project that can't.

    `fastro make <generator>` is checked against `[generators]` too, which is why this file says
    nothing about `make module` yet: that generator arrives with the module scaffold.
    """
    spans = [span or fenced for span, fenced in A_CODE_SPAN.findall((OVERLAY / path).read_text())]
    declared = _declared_commands()

    for named in (found for span in spans for found in A_FASTRO_COMMAND.findall(span)):
        verb, _, rest = named.partition(" ")
        if verb == "make" and rest:
            assert rest in CATALOG["generators"], named
        elif rest:
            assert named in declared, named
        else:
            assert verb in BUILT_IN_COMMANDS or verb in declared, named


def test_the_claude_file_points_at_the_agents_file():
    """One file for both, so instructions never drift: Claude Code reads `@AGENTS.md` as an import."""
    assert (OVERLAY / "CLAUDE.md").read_text().strip() == "@AGENTS.md"


def test_the_agents_file_tells_an_agent_what_it_must_not_edit():
    """The wiring is generated, and an agent editing it loses its work on the next sync."""
    text = (OVERLAY / "AGENTS.md").read_text()

    assert "src/wiring/" in text
    assert "fastro sync" in text
    assert "make module" not in text, "that generator does not exist yet"
