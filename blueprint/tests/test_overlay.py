"""What the overlay puts in a project, and what it is allowed to say.

Spec 2.1: the overlay's tree is copied into projects, and a `*.j2` file is rendered with the
spec 6.2 context and loses the suffix. So every path here lands in a project beside the files
core copies, and every name a template reads has to be one the tool passes.
"""

import re
import tomllib
from pathlib import Path
from typing import Any

import pytest
import yaml
from jinja2 import Environment, FileSystemLoader, StrictUndefined, meta

REPO_ROOT = Path(__file__).resolve().parents[2]

CATALOG = tomllib.loads((REPO_ROOT / "blueprint.toml").read_text())

OVERLAY = REPO_ROOT / CATALOG["blueprint"]["overlay"]

CONTEXT_NAMES = {"project", "blueprint", "fastro", "features", "options", "services", "params", "has"}
"""Spec 6.2, in full. A template reaching for anything else fails under `StrictUndefined`."""

BUILT_IN_COMMANDS = {"add", "check", "eject", "features", "init", "make", "new", "remove", "sync", "update"}
"""Fastro's own verbs, which take arguments of their own: `fastro add admin` names a feature, not
a command. Anything else after `fastro` has to be a command the catalog declares, and
`make <generator>` has to name one it has."""

A_FASTRO_COMMAND = re.compile(r"\bfastro(?:@(?:\{\{[^}]*\}\}|[^\s{]+))? ((?:[a-z][a-z0-9-]*)(?: [a-z][a-z0-9-]*)?)")
"""A command, however it is run: `fastro sync`, or `uvx fastro@{{ fastro.version }} sync`, or
`uvx fastro@0.1.0 sync`. Without the pin in the pattern every pinned command goes unread, and
with a pin that takes any non-space text, the template's own `{{ fastro.version }}` reads as one, leaving `fastro` as
the command."""

A_CODE_SPAN = re.compile(r"`([^`\n]+)`|```[a-z]*\n(.*?)```", re.DOTALL)
"""Only what is written as code is read as a command: prose says "generated by fastro from
blueprint.toml", and `fastro from` is not a command anybody runs. Each span is read on its own,
or two of them in one sentence would read as one command."""


def _context(features: tuple[str, ...] = (), **options: str) -> dict[str, Any]:
    """The spec 6.2 context, as the tool builds it for the overlay: no generator params."""
    return {
        "project": {"name": "Example App", "slug": "example-app"},
        "blueprint": {"name": CATALOG["blueprint"]["name"], "version": CATALOG["blueprint"]["version"]},
        "fastro": {"version": "0.1.0"},
        "features": list(features),
        "options": dict(options),
        "services": [],
        "params": {},
        "has": lambda name: name in features,
    }


def _files() -> list[Path]:
    return sorted(path for path in OVERLAY.rglob("*") if path.is_file())


def _declared_commands() -> set[str]:
    """Every command the catalog declares, the features' own included."""
    words = set(CATALOG.get("commands", {}))
    for feature in CATALOG["features"].values():
        words.update(feature.get("commands", {}))

    return words


def _landing(path: Path) -> Path:
    """Where an overlay file lands in a project: a `*.j2` is rendered and loses the suffix."""
    relative = path.relative_to(OVERLAY)

    return relative.with_suffix("") if relative.suffix == ".j2" else relative


def _received() -> set[str]:
    """Paths a project receives besides the overlay's: the repository's own files that aren't
    withheld, and every `[[wiring]]` path, which the tool writes whether or not this repository
    has the file yet."""
    written = {entry["path"] for entry in CATALOG["wiring"]}

    return written | {
        path.relative_to(REPO_ROOT).as_posix()
        for path in REPO_ROOT.rglob("*")
        if path.is_file() and not _withheld(path.relative_to(REPO_ROOT).as_posix())
    }


def _withheld(path: str) -> bool:
    return any(
        path == entry.rstrip("/") or (entry.endswith("/") and path.startswith(entry))
        for entry in CATALOG["blueprint"]["blueprint_only"]
    )


def test_the_overlay_is_where_the_catalog_says():
    assert OVERLAY.is_dir()
    assert _files(), OVERLAY


@pytest.mark.parametrize("path", [str(path.relative_to(OVERLAY)) for path in _files()])
def test_no_overlay_file_lands_on_a_file_a_project_already_receives(path: str):
    """Spec 1.27: two files at one path is refused, and a `[[wiring]]` path counts as taken even
    where this repository has no file yet. The overlay's `.gitignore` is the project's, which is
    why this repository's own is `blueprint_only`."""
    landing = _landing(OVERLAY / path).as_posix()

    assert landing not in _received(), landing


def test_no_two_overlay_files_land_on_one_path():
    """Spec 1.27: `x` and `x.j2` in the overlay would both land on `x`, and nothing says which
    of the two a project gets."""
    landings = [_landing(path).as_posix() for path in _files()]

    assert sorted(landings) == sorted(set(landings))


@pytest.mark.parametrize("path", [str(path.relative_to(OVERLAY)) for path in _files() if path.suffix == ".j2"])
def test_every_template_reads_only_what_the_tool_passes(path: str):
    """Spec 6.2: the context is fixed, so a template that asks for anything else renders nothing."""
    environment = Environment(loader=FileSystemLoader(OVERLAY), undefined=StrictUndefined, keep_trailing_newline=True)
    source = environment.loader.get_source(environment, path)[0]

    assert meta.find_undeclared_variables(environment.parse(source)) <= CONTEXT_NAMES


@pytest.mark.parametrize("path", [str(path.relative_to(OVERLAY)) for path in _files() if path.suffix == ".j2"])
def test_every_template_renders_for_a_project_with_no_features(path: str):
    """Core only is the harshest selection: every feature's lines have to be behind a condition."""
    environment = Environment(loader=FileSystemLoader(OVERLAY), undefined=StrictUndefined, keep_trailing_newline=True)

    assert environment.get_template(path).render(_context()).strip()


@pytest.mark.parametrize("path", [str(path.relative_to(OVERLAY)) for path in _files()])
def test_every_fastro_command_the_overlay_names_is_one_a_project_has(path: str):
    """A project told to run a command its blueprint doesn't declare is a project that can't.

    `fastro make <generator>` is checked against `[generators]` too, which is why this file says
    nothing about `make module` yet: that generator arrives with the module scaffold.
    """
    spans = [span or fenced for span, fenced in A_CODE_SPAN.findall((OVERLAY / path).read_text())]
    declared = _declared_commands()

    for named in (found for span in spans for found in A_FASTRO_COMMAND.findall(span)):
        verb, _, rest = named.partition(" ")
        if verb == "make" and rest:
            assert rest in CATALOG["generators"], named
        elif verb in BUILT_IN_COMMANDS:
            continue
        else:
            assert named in declared if rest else verb in declared, named


README = "README.md.j2"

FEATURE_LINES = {
    "accounts": "setup_initial_data",
    "admin": "/admin",
    "taskiq": "taskiq worker",
}
"""What the README writes for a feature, and nothing else writes: a project without the feature
must be told none of it."""


def _rendered(path: str, features: tuple[str, ...]) -> str:
    environment = Environment(loader=FileSystemLoader(OVERLAY), undefined=StrictUndefined, keep_trailing_newline=True)

    return environment.get_template(path).render(_context(features))


@pytest.mark.parametrize("features", [(), ("accounts",), tuple(CATALOG["features"])], ids=["core", "accounts", "all"])
def test_the_readme_tells_a_project_only_what_it_carries(features: tuple[str, ...]):
    """Each feature's lines appear exactly where the feature does. A README is the first thing a
    reader follows, and a step for something the project hasn't got is a step that fails."""
    rendered = _rendered(README, features)

    for feature, line in FEATURE_LINES.items():
        assert (line in rendered) == (feature in features), feature

    for name in CATALOG["features"]:
        if name not in features:
            assert not re.search(rf"\b{name}\b", rendered), name


def test_the_readme_describes_the_admin_panel_the_example_ships():
    """The README and `.env.example` go to the same project, so one can't say the panel is off
    while the other turns it on."""
    example = (REPO_ROOT / CATALOG["blueprint"]["python_root"] / ".env.example").read_text()
    rendered = _rendered(README, ("accounts", "admin"))
    shipped_off = "\nADMIN_ENABLED=false\n" in example

    assert ("ships switched off" in rendered) == shipped_off
    assert ("Set `ADMIN_ENABLED=true`" in rendered) == shipped_off


def test_the_readme_says_what_a_project_with_no_features_is():
    """Core only is a real answer, so the file says so rather than leaving the line empty."""
    rendered = _rendered(README, ())

    assert "Nothing optional is selected" in rendered
    assert "Selected:" not in rendered


def test_the_readme_names_the_features_a_project_selected():
    rendered = _rendered(README, ("accounts", "admin"))

    assert "Selected: accounts, admin." in rendered


@pytest.mark.parametrize("path", [str(path.relative_to(OVERLAY)) for path in _files() if path.suffix == ".j2"])
def test_every_fastro_command_a_template_writes_runs_the_tool_that_generated_the_project(path: str):
    """`uvx fastro@<version>` needs nothing installed first and pins the project to the tool it
    was generated with, so a reader never gets a newer tool's behaviour by accident.

    Templates only: `AGENTS.md` is written by hand and has no version to interpolate. In Markdown
    the commands are what is written as code; anywhere else every line is run, so the whole file
    counts. `fastro.toml` is a file and `fastro.version` a context value, so neither is read as a
    command, however a pattern escapes the dot.
    """
    text = (OVERLAY / path).read_text()
    spans = (
        [span or fenced for span, fenced in A_CODE_SPAN.findall(text)] if _landing(OVERLAY / path).suffix == ".md" else [text]
    )
    unpinned = []
    for span in spans:
        for found in re.finditer(r"fastro", span):
            before, after = span[: found.start()], span[found.end() :]
            if after.removeprefix("\\").startswith((".toml", ".version")):
                continue

            if not (before.endswith("uvx ") and after.startswith("@{{ fastro.version }}")):
                unpinned.append(span.strip()[:60])

    assert unpinned == []


WORKFLOW = ".github/workflows/ci.yml.j2"

PRE_COMMIT = ".pre-commit-config.yaml.j2"

BEFORE_FINISHING = ("ruff check .", "ruff format --check .", "mypy src scripts migrations tests", "pytest")
"""What an agent is told to run before finishing, which is what CI runs: one list, two files."""


@pytest.mark.parametrize("path", [WORKFLOW, PRE_COMMIT])
def test_the_yaml_a_project_receives_parses(path: str):
    """Rendered for the harshest selection, since a conditional that empties a list or leaves a
    dangling key is only visible once it is parsed."""
    assert yaml.safe_load(_rendered(path, ()))


def test_the_workflow_runs_what_the_agent_file_tells_an_agent_to_run():
    """An agent whose checks are looser than CI's finishes work that CI then rejects."""
    agents = (OVERLAY / "AGENTS.md").read_text()
    workflow = _rendered(WORKFLOW, ())

    for command in BEFORE_FINISHING:
        assert command in agents, command
        assert command in workflow, command


def test_the_workflow_installs_the_project_rather_than_this_workspace():
    """A project has one `pyproject.toml`, under the python root: `--all-packages` and a root
    lock are this repository's own shape, and neither is there."""
    workflow = yaml.safe_load(_rendered(WORKFLOW, ()))
    steps = workflow["jobs"]["check"]["steps"]
    installing = next(step for step in steps if step.get("name") == "Install")

    assert "--project backend" in installing["run"]
    assert "--all-packages" not in installing["run"]
    assert (
        "backend/uv.lock" in next(step for step in steps if step.get("name") == "Install uv")["with"]["cache-dependency-glob"]
    )


def test_every_pre_commit_hook_watches_paths_a_project_has():
    """A `files:` pattern naming `cli/` or `tools/` is a hook over nothing: those are the
    blueprint's own, and no project receives them."""
    hooks = yaml.safe_load(_rendered(PRE_COMMIT, ()))
    watched = [hook["files"] for repo in hooks["repos"] for hook in repo["hooks"] if "files" in hook]

    assert watched
    for pattern in watched:
        head = re.split(r"[(\[{|?*+\\]", pattern.removeprefix("^"))[0].rstrip("/")
        assert head in {"backend", "fastro.toml", "fastro\\.toml", ""} or not _withheld(head), pattern


def test_the_claude_file_points_at_the_agents_file():
    """One file for both, so instructions never drift: Claude Code reads `@AGENTS.md` as an import."""
    assert (OVERLAY / "CLAUDE.md").read_text().strip() == "@AGENTS.md"


def test_the_agents_file_tells_an_agent_what_it_must_not_edit():
    """The wiring is generated, and an agent editing it loses its work on the next sync."""
    text = (OVERLAY / "AGENTS.md").read_text()

    assert "src/wiring/" in text
    assert "fastro sync" in text
    assert "make module" not in text, "that generator does not exist yet"
