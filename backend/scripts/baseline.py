"""Write this project's baseline migration, and check that it recreates the models.

Run it once, from ``backend/``:

    python -m scripts.baseline
    python -m scripts.baseline --check

It starts a throwaway Postgres, autogenerates the revision against it, applies it to that
empty database, and compares the tables and indexes it created with the ones the models
declare. The revision is left in ``migrations/versions/`` to be committed. ``--check`` deletes
it again, so a project can be checked without gaining a migration.

A project that already has a revision is refused: a baseline is a project's first migration,
and autogenerating one against an empty database beside a history writes a revision that
recreates what the history already created.
"""

import argparse
import asyncio
import os
import subprocess
import sys
from pathlib import Path

backend_dir = Path(__file__).parent.parent
sys.path.append(str(backend_dir))

from sqlalchemy import Connection, inspect  # noqa: E402
from testcontainers.postgres import PostgresContainer  # noqa: E402

from src.infrastructure.database.registry import import_models  # noqa: E402
from src.infrastructure.database.session import Base, build_engine  # noqa: E402

IMAGE = "postgres:16-alpine"

MESSAGE = "baseline"
"""What the revision is named after, which alembic turns into the slug its file is named with."""

VERSIONS = Path("migrations/versions")

EXPOSED_PORT = 5432


class BaselineError(Exception):
    """What went wrong, as the line the script exits with."""


def alembic(*arguments: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run([sys.executable, "-m", "alembic", *arguments], capture_output=True, text=True)


def connection_settings(postgres: PostgresContainer) -> dict[str, str]:
    """The container, as the settings an alembic run reads the database from.

    ``DATABASE_URL`` is blanked because it wins over these: a configured one would send the
    autogenerate at the database the project really uses.
    """
    return {
        "POSTGRES_SERVER": postgres.get_container_host_ip(),
        "POSTGRES_PORT": str(postgres.get_exposed_port(EXPOSED_PORT)),
        "POSTGRES_USER": postgres.username,
        "POSTGRES_PASSWORD": postgres.password,
        "POSTGRES_DB": postgres.dbname,
        "DATABASE_URL": "",
    }


def database_url(postgres: PostgresContainer) -> str:
    details = connection_settings(postgres)

    return (
        f"postgresql+asyncpg://{details['POSTGRES_USER']}:{details['POSTGRES_PASSWORD']}"
        f"@{details['POSTGRES_SERVER']}:{details['POSTGRES_PORT']}/{details['POSTGRES_DB']}"
    )


def declared_schema() -> dict[str, list[str]]:
    """The tables and named indexes the models declare, beside the one alembic keeps itself."""
    import_models()
    declared = {
        name: sorted(str(index.name) for index in table.indexes if index.name is not None)
        for name, table in Base.metadata.tables.items()
    }
    declared["alembic_version"] = []

    return declared


def _reflected(connection: Connection) -> dict[str, list[str]]:
    """What is really there: an index a constraint brought with it is not counted twice."""
    inspector = inspect(connection)

    def indexes(table: str) -> list[str]:
        found = inspector.get_indexes(table)
        named = [index["name"] for index in found if not index.get("duplicates_constraint")]

        return sorted(name for name in named if name is not None)

    return {table: indexes(table) for table in sorted(inspector.get_table_names())}


async def created_schema(url: str) -> dict[str, list[str]]:
    """What applying the baseline left in the database."""
    engine = build_engine(url)
    try:
        async with engine.connect() as connection:
            return await connection.run_sync(_reflected)
    finally:
        await engine.dispose()


def _revisions() -> list[Path]:
    return sorted(VERSIONS.glob("*.py"))


def write_revision() -> Path:
    """Autogenerate the baseline, and return the one revision it wrote."""
    before = set(_revisions())
    autogenerated = alembic("revision", "--autogenerate", "-m", MESSAGE)
    if autogenerated.returncode != 0:
        raise BaselineError("autogenerate failed:\n" + autogenerated.stdout + autogenerated.stderr)

    written = [path for path in _revisions() if path not in before]
    if len(written) != 1:
        raise BaselineError(f"autogenerate wrote {len(written)} revisions, and a baseline is one")

    if not written[0].name.endswith(f"_{MESSAGE}.py"):
        raise BaselineError(f"autogenerate wrote {written[0].name}, which is not the baseline")

    return written[0]


def write_baseline(url: str, *, keeping: bool) -> str:
    """Write the baseline and apply it, and say what it recreated."""
    declared = declared_schema()
    revision = write_revision()
    try:
        applied = alembic("upgrade", "head")
        if applied.returncode != 0:
            raise BaselineError("upgrade failed:\n" + applied.stdout + applied.stderr)

        created = asyncio.run(created_schema(url))
        if created != declared:
            raise BaselineError(f"the baseline left {created}, while the models declare {declared}")
    finally:
        if not keeping:
            revision.unlink(missing_ok=True)

    indexes = sum(len(names) for names in declared.values())

    return f"a baseline of {len(declared) - 1} tables and {indexes} indexes applies to an empty database"


def _refuse_a_history() -> None:
    history = _revisions()
    if history:
        names = ", ".join(path.name for path in history)

        raise BaselineError(f"this project already has {names}, and a baseline is a project's first revision")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Write this project's baseline migration against a throwaway database.")
    parser.add_argument("--check", action="store_true", help="delete the revision afterwards, leaving the tree as it was")
    arguments = parser.parse_args(argv)

    os.environ["TESTCONTAINERS_RYUK_DISABLED"] = "true"
    try:
        _refuse_a_history()
        with PostgresContainer(IMAGE) as postgres:
            os.environ.update(connection_settings(postgres))
            print(write_baseline(database_url(postgres), keeping=not arguments.check))
    except BaselineError as error:
        print(error, file=sys.stderr)

        return 1

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
