"""The database-backed store crudauth keeps its server-side state in.

Its two tables are declared on ``Base.metadata`` whatever the settings say, so
``CREATE_TABLES_ON_STARTUP`` creates them and every autogenerated migration holds them.
Declaring them only where a setting selected the store made the schema depend on a
runtime choice: a baseline generated with the default backends lacked the tables, so
moving to ``SESSION_BACKEND=database`` later found none, and autogenerating with the
default against a database-backed deployment wrote a revision that dropped them.

``database_store`` is the store itself, and stays ``None`` unless ``SESSION_BACKEND`` or
``RATE_LIMITER_BACKEND`` names ``database``: the tables are part of the schema, using them
is a setting.
"""

from crudauth import DatabaseStore
from sqlalchemy import MetaData
from sqlalchemy.ext.asyncio import async_sessionmaker

from ..config.enums import RateLimiterBackend, SessionBackend
from ..config.settings import settings
from ..database.session import Base, get_session_factory


def store_is_selected() -> bool:
    """Whether a setting puts sessions or the lockout counters in the database."""
    return settings.SESSION_BACKEND == SessionBackend.DATABASE or settings.RATE_LIMITER_BACKEND == RateLimiterBackend.DATABASE


def build_store(metadata: MetaData | None = None) -> DatabaseStore:
    """A store declaring the two tables, on the app's own engine where it will be used.

    Args:
        metadata: Where to declare the two tables. The project's own by default, which is
            what puts them in ``create_all`` and in an autogenerated migration.

    Note:
        Where no setting selected the store, its session factory is left unbound: nothing
        reads it, and binding one would open an engine a project that keeps its sessions
        in Redis has no use for.
    """
    sessions = get_session_factory() if store_is_selected() else async_sessionmaker()

    return DatabaseStore(sessions, metadata=metadata if metadata is not None else Base.metadata)


store = build_store()
"""The store, whose construction is what declares ``crudauth_store`` and ``crudauth_counters``."""

database_store = store if store_is_selected() else None
